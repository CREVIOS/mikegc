// Writes docs/examples/bangladesh/: each Bangladesh use case's draft and its
// redline (real Word tracked changes, made by Spectre's edit engine), and a
// README with the cover notes and the changes. Run from backend/:
//   npx tsx scripts/build-bangladesh-examples.ts [outDir] [jsonOut]
import { mkdir, writeFile } from "fs/promises";
import path from "path";
import { redlineUseCase } from "../src/lib/bangladesh/demo/buildExamples";
import { BANGLADESH_USE_CASES } from "../src/lib/bangladesh/demo/useCases";

const outDir = path.resolve(process.argv[2] ?? path.join(__dirname, "../../docs/examples/bangladesh"));
const jsonOut = process.argv[3];

async function main() {
    await mkdir(outDir, { recursive: true });
    const readme: string[] = [
        "# Bangladesh corporate examples",
        "",
        "Five foreign-drafted documents and the markup a Bangladeshi lawyer makes to each. The `-redline.docx` files carry real Word tracked changes made by Spectre's edit engine (author \"Spectre\"): open one in Word and use Review → Accept or Reject. Every change cites the provision it rests on. Each file is regenerated by `backend/scripts/build-bangladesh-examples.ts`, and `backend/src/lib/bangladesh/demo/__tests__/useCases.test.ts` checks that every edit applies and lands on word boundaries.",
        "",
        "These are demonstrations, not advice: confirm the points listed under \"To confirm\" before using any wording.",
        "",
    ];
    const data = [];
    for (const [index, useCase] of BANGLADESH_USE_CASES.entries()) {
        const n = String(index + 1).padStart(2, "0");
        const { draft, redline, changes } = await redlineUseCase(useCase);
        await writeFile(path.join(outDir, `${n}-${useCase.id}-draft.docx`), draft);
        await writeFile(path.join(outDir, `${n}-${useCase.id}-redline.docx`), redline);
        readme.push(
            `## ${index + 1}. ${useCase.title}`,
            "",
            `Acting for ${useCase.actingFor}. ${useCase.context}`,
            "",
            `Files: [draft](${n}-${useCase.id}-draft.docx) · [redline](${n}-${useCase.id}-redline.docx)`,
            "",
            "| Clause change | Why | Provision |",
            "| --- | --- | --- |",
            ...changes.map((c) => {
                const before = c.deletedText ? `~~${c.deletedText.slice(0, 80)}${c.deletedText.length > 80 ? "…" : ""}~~ ` : "";
                const after = c.insertedText ? `**${c.insertedText.trim().slice(0, 80)}${c.insertedText.length > 80 ? "…" : ""}**` : "";
                return `| ${(before + after).replace(/\|/g, "\\|")} | ${c.reason} | ${c.provision} |`;
            }),
            "",
            "**Cover note**",
            "",
            useCase.coverNote,
            "",
            "**To confirm**",
            "",
            ...useCase.toConfirm.map((item) => `- ${item}`),
            "",
        );
        data.push({ ...useCase, changes: changes.map(({ deletedText, insertedText, contextBefore, contextAfter, reason, provision }) => ({ deletedText, insertedText, contextBefore, contextAfter, reason, provision })) });
    }
    await writeFile(path.join(outDir, "README.md"), readme.join("\n"));
    if (jsonOut) await writeFile(jsonOut, JSON.stringify(data, null, 2));
    console.log(`Wrote ${BANGLADESH_USE_CASES.length * 2} documents to ${outDir}`);
}

main().catch((error) => {
    console.error(error);
    process.exit(1);
});
